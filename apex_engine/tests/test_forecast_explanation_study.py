def test_six_families_and_baselines_portable_checkpoint_replay(study):
    report = verify_explanation_study(study)
    assert report["verified"] and not report["task_closure_eligible"]
    assert report["decision"] == "SIMULATED_EXECUTION_ONLY"
    assert report["methods"] == 8 and report["origins"] == 16
    assert report["maximum_reload_difference_kj"] <= 1e-6
    result = json.loads((study/"results.json").read_text(encoding="utf-8"))
    assert result["schema_version"] == VERSION
    assert result["target_quality"] == "PROXY_NOT_MEASURED" and not result["promotion"]
    # The old forecast smoke fixture is not generated by the physical energy proxy.
    # Refuse its histories, do not fabricate successful feasible counterfactuals.
    assert all(c["counterfactual"]["selected_index"] is None for m in result["models"].values() for c in m["cases"])


def test_every_checkpoint_family_works_with_temporal_black_box_interface(study):
    reference = study/"reference"
    summary = json.loads((reference/"summary.json").read_text(encoding="utf-8"))
    stored = json.loads((reference/"scaler.json").read_text(encoding="utf-8"))
    scaler = ForecastScaler(*(np.array(stored[k]) for k in ("input_mean", "input_std", "target_mean", "target_std")))
    old = torch.get_num_threads()
    torch.set_num_threads(1)
    try:
        with np.load(reference/"windows.npz", allow_pickle=False) as data:
            x, static = data["dynamic"], data["static"]
        rng_before = torch.random.get_rng_state().clone()
        for record in summary["records"]:
            predictor = FrozenForecastPredictor(reference/record["checkpoint"], record, scaler, summary["vocabulary"])
            report, arrays = temporal_explanation(predictor, x[0], static[0], x[8:16], x[1])
            assert report["status"] in ("RELIABLE_MODEL_DIAGNOSTIC", "ABSTAIN_UNSTABLE_OR_UNFAITHFUL")
            assert all(np.isfinite(v).all() for v in arrays.values())
        assert torch.equal(rng_before, torch.random.get_rng_state())
    finally:
        torch.set_num_threads(old)


def test_metadata_freeze_reads_no_binary_payloads_and_is_immutable(study, tmp_path, monkeypatch):
    monkeypatch.setattr(np, "load", lambda *a, **k: pytest.fail("metadata preregistration read a binary payload"))
    first = make_cohort(study/"reference", study/"evaluation", "smoke")
    assert first["outcomes_used"] is False
    assert first == make_cohort(study/"reference", study/"evaluation", "smoke")
    path = tmp_path/"cohort.json"
    freeze_cohort(study/"reference", study/"evaluation", path, "smoke")
    with pytest.raises(FileExistsError):
        freeze_cohort(study/"reference", study/"evaluation", path, "smoke")


