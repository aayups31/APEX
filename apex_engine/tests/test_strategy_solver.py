def test_solver_cli_artifact_inventory_seals_and_exclusive_output(tmp_path):
    from typer.testing import CliRunner

    from apexsim.cli import app
    from apexsim.provenance import file_sha256, payload_sha256

    output = tmp_path / "acceptance"
    result = CliRunner().invoke(app, ["strategy-solver-demo", "--output", str(output)])
    assert result.exit_code == 0, result.output
    summary = json.loads(result.output)
    assert summary["passed"] and summary["reference_cases"] == 2 and summary["max_absolute_regret_s"] < 1e-6
    assert summary["maturity"] == "R0" and not summary["global_solver_optimality_certified"]
    for name in ("summary", "manifest"):
        sealed = json.loads((output / f"{name}.json").read_text())
        digest = sealed.pop("content_sha256")
        assert payload_sha256(sealed) == digest
    manifest = json.loads((output / "manifest.json").read_text())
    assert set(manifest["files"]) == {"cases.json", "summary.json"}
    assert set(p.name for p in output.iterdir()) == {*manifest["files"], "manifest.json"}
    for name, info in manifest["files"].items():
        assert info == {"sha256": file_sha256(output/name), "bytes": (output/name).stat().st_size}
    cases = json.loads((output / "cases.json").read_text())
    assert len(cases) == 3 and cases[-1]["reference"] is None and cases[-1]["regret_s"] is None
    before = {p.name: p.read_bytes() for p in output.iterdir()}
    result = CliRunner().invoke(app, ["strategy-solver-demo", "--output", str(output)])
    assert isinstance(result.exception, FileExistsError)
    assert before == {p.name: p.read_bytes() for p in output.iterdir()}


def test_failed_solver_acceptance_creates_no_artifacts(tmp_path, monkeypatch):
    from apexsim.examples import strategy_solver_demo

    original = strategy_solver_demo.tiny_continuous_reference
    def wrong(*args, **kwargs):
        result = original(*args, **kwargs)
        return replace(result, race_time_s=result.race_time_s - 1)
    monkeypatch.setattr(strategy_solver_demo, "tiny_continuous_reference", wrong)
    output = tmp_path / "failed"
    with pytest.raises(ValueError, match="missed the independent tiny optimum"):
        strategy_solver_demo.run_strategy_solver_demo(output)
    assert not output.exists()
