DRY = (TyreCompound.SOFT, TyreCompound.MEDIUM, TyreCompound.HARD)
PLAN = (None, TyreCompound.SOFT, None)


def tiny_model(linear=False):
    p = PaperStrategyParameters(total_laps=3, initial_fuel_kg=6, battery_capacity_mj=1,
                                battery_delta_min_mj=-1, battery_delta_max_mj=.5)
    if linear:
        p = replace(p, battery_deploy_time_s_per_mj=.4, battery_recharge_time_s_per_mj=.4)
    return PaperStrategyModel(p, wear_coefficients={c: TireWearCoefficients(1., 0., .01) for c in DRY})


@pytest.mark.parametrize("linear", [False, True])
def test_solver_recovers_independent_continuous_vertex_optimum(linear):
    model = tiny_model(linear)
    reference = tiny_continuous_reference(model, pit_window=(1, 1))
    result = EnumeratedStrategySolver(model).solve(pit_window=(1, 1))
    assert result.solution.smooth_race_time_s == pytest.approx(reference.race_time_s, abs=1e-6, rel=0)
    assert result.report["all_plans_have_accepted_solution"]
    assert result.report["accepted_attempts"] > 0
    assert not result.report["global_optimality_certified"]
    assert result.report["plans"] == 2
    assert abs(result.solution.terminal_fuel_mj) <= 1e-7
    assert abs(result.solution.terminal_battery_mj) <= 1e-7
    assert result.solution.max_primal_violation <= 1e-7
    ratios = [a.fuel_energy_mj/model.p.nominal_fuel_energy_mj() for a in result.solution.actions]
    np.testing.assert_allclose(ratios, [1.1, 1., .9], atol=1e-5, rtol=0)
    if linear:
        # Independently hand calculated, not generated by the graph/reference code.
        assert reference.race_time_s == pytest.approx(305.626825, abs=1e-10, rel=0)


def test_scalar_replay_and_full_problem_derivatives_match_casadi():
    problem = FixedPlanProblem(tiny_model(), PLAN)
    for start in energy_starts(problem.model):
        solution = problem.replay(start)
        assert solution.max_legacy_action_adjustment_mj < 1e-10
        assert abs(solution.smooth_race_time_s-solution.original_race_time_s) <= 3*problem.map.approximation_bound_s
        gradient, jacobian = np.asarray(problem.gradient(start)).reshape(-1), np.asarray(problem.jacobian(start))
        for i in range(len(start)):
            offset = np.eye(len(start))[i]*1e-5
            fd = (float(problem.objective(start+offset))-float(problem.objective(start-offset)))/2e-5
            assert gradient[i] == pytest.approx(fd, abs=1e-6, rel=1e-5)
            fd_g = np.asarray(problem.constraints(start+offset)-problem.constraints(start-offset)).reshape(-1)/2e-5
            np.testing.assert_allclose(jacobian[:, i], fd_g, atol=1e-8, rtol=1e-5)


def test_mass_coupled_wear_is_feasible_but_cannot_claim_tiny_certificate():
    model = PaperStrategyModel(PaperStrategyParameters(total_laps=6, initial_fuel_kg=12,
                                                      battery_capacity_mj=2, battery_delta_min_mj=-1))
    result = EnumeratedStrategySolver(model).solve(pit_window=(2, 2))
    assert result.solution.max_primal_violation <= 1e-7
    assert not result.report["global_optimality_certified"]
    assert all(0 <= s.tyre_wear <= 1.25 for s in result.solution.states)
    with pytest.raises(ValueError, match="mass-independent"):
        tiny_continuous_reference(model)


def test_successful_but_worse_local_solve_keeps_checked_feasible_incumbent(monkeypatch):
    model = tiny_model()
    class Backend:
        def __init__(self, problem):
            self.problem = problem
        def __call__(self, **kwargs):
            x = energy_starts(model)[0]
            return {"x": x, "f": float(self.problem.objective(x))}
        def stats(self):
            return {"success": True, "return_status": "fixture_success", "iter_count": 1}
    monkeypatch.setattr(FixedPlanProblem, "backend", lambda self, settings: Backend(self))
    result = EnumeratedStrategySolver(model).solve(pit_window=(1, 1))
    assert result.solution.smooth_race_time_s == pytest.approx(
        tiny_continuous_reference(model, pit_window=(1, 1)).race_time_s, abs=1e-10, rel=0)
    assert result.report["attempts"][result.report["selected_attempt"]]["selected_source"] == "feasible_start"
    assert not result.report["global_optimality_certified"]


